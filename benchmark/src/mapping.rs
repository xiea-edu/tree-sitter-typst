use typst_syntax::SyntaxKind;

/// Only direct, one-to-one constructs exposed as named nodes by all three parsers.
/// Root handling is separate because Typst uses `Markup` for nested markup too.
pub fn official(kind: SyntaxKind) -> Option<&'static str> {
    use SyntaxKind::*;
    Some(match kind {
        Linebreak => "linebreak",
        Escape => "escape",
        SmartQuote => "smart_quote",
        Strong => "strong",
        Emph => "emphasis",
        Link => "link",
        Label => "label",
        Ref => "reference",
        Heading => "heading",
        TermItem => "term_item",
        Equation => "equation",
        Math => "math",
        MathAlignPoint => "math_align_point",
        MathAttach => "math_attach",
        MathPrimes => "math_primes",
        MathFrac => "math_fraction",
        MathRoot => "math_root",
        Code => "embedded_code",
        Bool => "boolean",
        Str => "string",
        CodeBlock => "code_block",
        ContentBlock => "content_block",
        Closure => "closure",
        LetBinding => "let_binding",
        SetRule => "set_rule",
        ShowRule => "show_rule",
        Contextual => "contextual",
        Conditional => "conditional",
        WhileLoop => "while_loop",
        ForLoop => "for_loop",
        ModuleImport => "module_import",
        ModuleInclude => "module_include",
        FuncReturn => "return",
        None => "none",
        Auto => "auto",
        _ => return std::option::Option::None,
    })
}

