static bool uc_lookup(const uint32_t (*table)[2], size_t n, int32_t c) {
  if (c < 0) return false;
  uint32_t u = (uint32_t)c;
  size_t lo = 0, hi = n;
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (u < table[mid][0]) hi = mid;
    else if (u > table[mid][1]) lo = mid + 1;
    else return true;
  }
  return false;
}

#define UC_IN(tbl, c) uc_lookup((tbl), sizeof(tbl) / sizeof((tbl)[0]), (c))

/* Rust's `char::is_alphabetic`. */
static bool is_alpha(int32_t c) {
  if (c < 128) return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
  return UC_IN(UC_ALPHA, c);
}

/* Rust's `char::is_alphanumeric` — Alphabetic plus the Nd/Nl/No categories. */
static bool is_alnum(int32_t c) {
  if (c < 128) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
  }
  return UC_IN(UC_ALPHA, c) || UC_IN(UC_NUMERIC, c);
}

/*
 * Rust's `char::is_whitespace` restricted to non-ASCII, which is the only form the
 * callers want: ASCII whitespace is trivia handled by `is_space`, while a non-ASCII
 * space is content that gets a `Text` node of its own.
 */
static bool is_non_ascii_space(int32_t c) {
  if (c < 128) return false;
  return UC_IN(UC_SPACE, c);
}

/*
 * ASCII whitespace only, deliberately.
 *
 * Typst stops a text run at *any* Unicode whitespace, but then emits that character as a
 * one-character `Text` rather than discarding it — `発行日時　#x` is two text nodes, the
 * second being just the ideographic space. So U+3000 and friends are content here, not
 * trivia; `is_text_stop` ends the run at them and the dispatcher gives them their own
 * token.
 */
static inline bool is_space(int32_t c) {
  return c == ' ' || c == '\t' || c == '\r' || c == '\n' || c == 0x0b || c == 0x0c;
}

/*
 * Whether `c` counts as being "in a word" for the `*`/`_` delimiter test.
 *
 * Typst's `Lexer::in_word` is alphanumeric *minus* the Han, Hiragana, Katakana and Hangul
 * scripts. Those are written without spaces between words, so treating a `*` between two
 * of their characters as literal text — the way `a*b` is text in English — would make
 * emphasis impossible to write in CJK at all. `以*本*` is therefore a strong, while
 * `a*b*` is not.
 *
 * The ranges below are the assigned blocks of those four scripts. Characters that are not
 * alphanumeric to begin with never reach the exclusion, so a few punctuation code points
 * falling inside a range does no harm.
 */
static bool is_wordy(int32_t c) {
  if (!is_alnum(c)) return false;
  if (c < 0x1100) return true;  // the common case: Latin, Greek, Cyrillic, Hebrew, Thai

  if ((c >= 0x1100 && c <= 0x11FF) ||    // Hangul Jamo
      (c >= 0x2E80 && c <= 0x2EFF) ||    // CJK Radicals Supplement
      (c >= 0x3005 && c <= 0x303B) ||    // Han iteration marks and friends
      (c >= 0x3041 && c <= 0x30FF) ||    // Hiragana and Katakana
      (c >= 0x3131 && c <= 0x318E) ||    // Hangul Compatibility Jamo
      (c >= 0x31F0 && c <= 0x31FF) ||    // Katakana Phonetic Extensions
      (c >= 0x3400 && c <= 0x4DBF) ||    // CJK Extension A
      (c >= 0x4E00 && c <= 0x9FFF) ||    // CJK Unified Ideographs
      (c >= 0xA960 && c <= 0xA97F) ||    // Hangul Jamo Extended-A
      (c >= 0xAC00 && c <= 0xD7FF) ||    // Hangul Syllables and Extended-B
      (c >= 0xF900 && c <= 0xFAFF) ||    // CJK Compatibility Ideographs
      (c >= 0xFF66 && c <= 0xFF9F) ||    // halfwidth Katakana
      (c >= 0x20000 && c <= 0x3134F)) {  // CJK supplementary planes
    return false;
  }
  return true;
}

/* Typst identifiers continue on XID_Continue, `_` and `-`. `is_alnum` is a practical
 * stand-in for XID_Continue here; the exact Unicode tables only matter for identifiers
 * in code mode, which the grammar handles with a real property escape. */
static inline bool is_id_continue(int32_t c) {
  return is_alnum(c) || c == '_' || c == '-';
}

/* Valid inside `<label>` and after `@`: identifier characters plus `:` and `.`. */
static inline bool is_label_char(int32_t c) {
  return is_id_continue(c) || c == ':' || c == '.';
}

/*
 * Characters that end a text run (`Lexer::text`'s TABLE), plus non-ASCII whitespace.
 * Several of these resume the same run — see `scan_text`.
 */
static bool is_text_stop(int32_t c) {
  switch (c) {
    case ' ': case '\t': case '\n': case 0x0b: case 0x0c: case '\r':
    case '\\': case '/': case '[': case ']': case '~': case '-': case '.':
    case '\'': case '"': case '*': case '_': case ':': case 'h': case '`':
    case '$': case '<': case '>': case '@': case '#':
      return true;
    default:
      return is_non_ascii_space(c);
  }
}

