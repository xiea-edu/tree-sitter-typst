//! Generate the external math lexer's Unicode data from the crates pinned in the oracle lockfile.
//! With those crate directories as $SEG and $ID, run:
//!   rustc --edition=2021 --crate-type=rlib --crate-name segmentation_tables $SEG/src/tables.rs
//!   rustc --edition=2021 --crate-type=rlib --crate-name unicode_ident $ID/src/lib.rs
//!   rustc --edition=2021 gen-math-unicode.rs --extern segmentation_tables=libsegmentation_tables.rlib --extern unicode_ident=libunicode_ident.rlib
//!   ./gen-math-unicode > src/math_unicode.h
use segmentation_tables::{derived_property, grapheme, is_incb_linker};
use std::io::{self, BufWriter, Write};

fn main() -> io::Result<()> {
    let mut out = BufWriter::new(io::stdout().lock());
    writeln!(out, "/* Generated by tools/gen-math-unicode.rs. Unicode {:?}. */", segmentation_tables::UNICODE_VERSION)?;
    writeln!(out, "/* Derived from unicode-segmentation and unicode-ident; see math_unicode.LICENSE. */")?;
    writeln!(out, "static const MathCharRange MATH_CHAR_RANGES[] = {{")?;
    let mut previous = None;
    for code in 0..=0x10ffff {
        let c = char::from_u32(code).unwrap_or(char::REPLACEMENT_CHARACTER);
        let (_, _, cat) = grapheme::grapheme_category(c);
        let flags = u8::from(unicode_ident::is_xid_start(c))
            | (u8::from(unicode_ident::is_xid_continue(c)) << 1)
            | (u8::from(derived_property::InCB_Extend(c)) << 2)
            | (u8::from(is_incb_linker(c)) << 3);
        if previous != Some((cat, flags)) {
            writeln!(out, "  {{0x{code:X}, {cat:?}, {flags}}},")?;
            previous = Some((cat, flags));
        }
    }
    writeln!(out, "}};")
}
